// Every control is now a data-action routed through the ACTIONS registry. A mis-wired action
// throws nothing - it just silently does nothing - so this suite clicks each one for real and
// checks it had its effect. It also asserts no inline handlers remain anywhere.
module.exports = {
  name: 'Delegated controls',
  run: async ({ page, ok, base }) => {
    await page.goto(`${base}/index.html`);
    await page.waitForTimeout(500);

    // Several actions appear on more than one screen (title, citadel, map all offer some of
    // them), so always drive the one the player can actually see.
    const click = async sel => { await page.locator(`${sel}:visible`).first().click(); await page.waitForTimeout(180); };
    const shown = id => page.$eval(`#${id}`, e => getComputedStyle(e).display);
    const state = fn => page.evaluate(fn);
    // Resolving an action schedules the next turn on a timer, which would re-render the deck
    // underneath us. Stand combat down, let any queued timer fire as a no-op, then stage the
    // turn we want to drive.
    const stageTurn = async fn => {
      await page.evaluate(() => { combatActive = false; });
      await page.waitForTimeout(900);
      await page.evaluate(fn);
      await page.waitForTimeout(150);
    };

    // no inline handlers survive in either file
    const sources = await page.evaluate(async () => {
      const html = await (await fetch('index.html')).text();
      const js = await (await fetch('game.js')).text();
      return { html: (html.match(/on(click|change|input)=/g) || []).length,
               js: (js.match(/onclick=/g) || []).length };
    });
    ok('no inline handlers left in the markup', sources.html === 0);
    ok('no inline handlers generated by the engine', sources.js === 0);

    // ---- title screen ----
    await state(() => { localStorage.clear(); bossSkulls = 6; saveMeta(); renderTitleScreen(); });
    await click('[data-action="citadel"]');
    ok('citadel opens from the title', await shown('screen-citadel') === 'flex');
    await click('[data-action="buy-meta"][data-kind="SCRAP"]');
    ok('buy-meta spends a skull', await state(() => bossSkulls) === 5);
    await click('[data-action="title"]');
    ok('title returns from the citadel', await shown('screen-title') === 'flex');

    await click('[data-action="slot"][data-slot="1"]');
    ok('an empty slot opens difficulty select',
      await page.$eval('#difficulty-menu-container', e => getComputedStyle(e).display) === 'flex');
    await click('[data-action="title"]');
    ok('cancel returns to the slot list',
      await page.$eval('#title-menu-container', e => getComputedStyle(e).display) === 'flex');
    await click('[data-action="slot"][data-slot="1"]');
    await click('[data-action="new-game"][data-diff="0.75"]');
    ok('new-game starts a run at the chosen difficulty',
      await shown('screen-map') === 'flex' && await state(() => difficultyMult) === 0.75);

    // ---- settings ----
    const speed0 = await state(() => globalSettings.combatSpeed);
    await click('[data-action="settings-open"]');
    ok('settings open', await shown('screen-settings') === 'flex');
    await click('[data-action="toggle-speed"]');
    ok('toggle-speed changes combat speed', await state(() => globalSettings.combatSpeed) !== speed0);
    const sfx0 = await state(() => globalSettings.sfx);
    await click('[data-action="toggle-sfx"]');
    ok('toggle-sfx flips the audio setting', await state(() => globalSettings.sfx) !== sfx0);
    await click('[data-action="settings-close"]');
    ok('settings close', await shown('screen-settings') === 'none');

    // ---- outpost ----
    await state(() => { scrap = 999; materials = { parts: 9, chems: 9, tech: 9 }; });
    await click('[data-action="outpost"]');
    ok('outpost opens from the map', await shown('screen-outpost') === 'flex');
    await click('[data-action="outpost-tab"][data-tab="WORKBENCH"]');
    ok('workbench tab switches', await shown('outpost-workbench-view') === 'flex');
    const inv0 = await state(() => inventory.length);
    await click('[data-action="craft"][data-item="MED_STIM"]');
    ok('craft adds an item', await state(() => inventory.length) === inv0 + 1);
    const mats0 = await state(() => materials.parts + materials.chems + materials.tech);
    await click('[data-action="breakdown"]');
    ok('breakdown converts scrap into materials',
      await state(() => materials.parts + materials.chems + materials.tech) === mats0 + 1);

    await click('[data-action="outpost-tab"][data-tab="CYBER"]');
    ok('cybernetics tab switches', await shown('outpost-cyber-view') === 'flex');
    const hp0 = await state(() => playerRoster[0].maxHp);
    await click('[data-action="augment"][data-kind="PLATING"]');
    ok('augment applies to the operator', await state(() => playerRoster[0].maxHp) === hp0 + 20);

    await click('[data-action="outpost-tab"][data-tab="ROSTER"]');
    ok('roster tab switches', await shown('outpost-roster-view') === 'flex');
    const dmg0 = await state(() => playerRoster[0].dmgBase);
    await click('[data-action="buy-upg"][data-kind="DMG"]');
    ok('buy-upg raises damage', await state(() => playerRoster[0].dmgBase) === dmg0 + 3);

    await click('[data-action="pos-menu"]');
    ok('pos-menu opens the position selector', await state(() => activePosSelector) !== null);
    await click('[data-action="assign-slot"][data-slot="0"]');
    ok('assign-slot benches the operator',
      await state(() => playerRoster[0].gridPos) === 0 && await state(() => activePosSelector) === null);
    await click('[data-action="pos-menu"]');
    await click('[data-action="selector-cancel"]');
    ok('selector-cancel closes the selector', await state(() => activePosSelector) === null);

    await state(() => { playerRoster[0].gridPos = 1; playerRoster[0].perkPoints = 1; playerRoster[0].trait = null; renderOutpost(); });
    await click('[data-action="perk-menu"]');
    ok('perk-menu opens the perk selector', await state(() => activePerkSelector) !== null);
    await click('[data-action="assign-perk"][data-perk="VETERAN"]');
    ok('assign-perk grants the trait', await state(() => playerRoster[0].trait) === 'VETERAN');

    await state(() => { playerRoster[0].hp = 1; renderOutpost(); });
    await click('[data-action="medbay"][data-mode="HEAL"]');
    ok('medbay heals the operator', await state(() => playerRoster[0].hp) > 1);

    const invBefore = await state(() => inventory.length);
    await click('[data-action="sell-item"]');
    ok('sell-item removes an item', await state(() => inventory.length) === invBefore - 1);
    await click('[data-action="map"]');
    ok('map returns from the outpost', await shown('screen-map') === 'flex');

    // ---- map nodes ----
    await state(() => { currentTier = 1; currentSector = 1; renderMap(); });
    await click('.map-node:not([disabled])');
    ok('a map node starts combat', await shown('screen-combat') === 'flex');

    // ---- combat deck ----
    await stageTurn(() => {
      playerRoster.forEach(p => { p.hp = p.maxHp; });
      const medic = playerRoster.find(p => p.classType === 'MEDIC');
      medic.gridPos = 1; medic.stunnedTurns = 0;
      const foes = activeEntities.filter(e => !e.isPlayer);
      foes.forEach(f => { f.hp = f.maxHp; });
      activeEntities = [medic, ...foes]; turnQueue = [medic, ...foes];
      activeIndex = 0; combatActive = true; pendingAction = null; renderField();
    });
    await click('[data-action="queue"][data-move="PISTOL"]');
    ok('queue arms an ability', await state(() => pendingAction) === 'PISTOL');
    await click('[data-action="cancel"]');
    ok('cancel clears the armed ability', await state(() => pendingAction) === null);
    await click('[data-action="queue"][data-move="PISTOL"]');
    const ehp0 = await state(() => activeEntities.find(e => !e.isPlayer).hp);
    await click('.targetable-enemy');
    ok('target resolves the attack onto the enemy',
      await state(() => activeEntities.find(e => !e.isPlayer).hp) < ehp0);

    // bag -> use a consumable on an ally
    await stageTurn(() => {
      const medic = playerRoster.find(p => p.classType === 'MEDIC');
      medic.hp = 10; inventory = ['MED_STIM'];
      activeEntities.filter(e => !e.isPlayer).forEach(f => { f.hp = f.maxHp; });
      activeIndex = turnQueue.indexOf(medic); pendingAction = null; combatActive = true; renderField();
    });
    await click('[data-action="bag"]');
    ok('bag lists the inventory', (await page.$$('[data-action="queue"][data-move="ITEM_MED"]')).length === 1);
    await click('[data-action="queue"][data-move="ITEM_MED"]');
    await click('.targetable-ally');
    ok('use-item heals and consumes the stim',
      await state(() => playerRoster.find(p => p.classType === 'MEDIC').hp) > 10 &&
      await state(() => inventory.length) === 0);

    // self action + stun skip
    await stageTurn(() => {
      const bruiser = playerRoster.find(p => p.classType === 'BRUISER');
      bruiser.gridPos = 2; bruiser.hp = bruiser.maxHp; bruiser.armor = 0;
      bruiser.cooldowns.iron_guard = 0; bruiser.stunnedTurns = 0;
      if (!turnQueue.includes(bruiser)) { turnQueue.push(bruiser); activeEntities.push(bruiser); }
      activeIndex = turnQueue.indexOf(bruiser); pendingAction = null; combatActive = true; renderField();
    });
    await click('[data-action="self"][data-move="IRON_GUARD"]');
    ok('self action applies Iron Guard armour',
      await state(() => playerRoster.find(p => p.classType === 'BRUISER').armor) >= 15);

    await stageTurn(() => {
      const b = playerRoster.find(p => p.classType === 'BRUISER');
      b.stunnedTurns = 2; activeIndex = turnQueue.indexOf(b);
      pendingAction = null; combatActive = true; renderField();
    });
    await click('[data-action="skip-turn"]');
    ok('skip-turn burns a stun turn',
      await state(() => playerRoster.find(p => p.classType === 'BRUISER').stunnedTurns) === 1);

    // ---- loot ----
    await state(() => {
      combatActive = true; currentTier = 1;
      activeEntities.filter(e => !e.isPlayer).forEach(e => e.hp = 0);
      playerRoster.forEach(p => { if (p.gridPos > 0) p.hp = p.maxHp; });
      checkWinState();
    });
    const tier0 = await state(() => currentTier);
    await click('[data-action="loot"]');
    ok('loot banks the reward and advances the tier', await state(() => currentTier) === tier0 + 1);

    // ---- event and camp nodes ----
    await state(() => { initiateEvent(); });
    await page.waitForTimeout(200);
    await click('[data-action="event-choice"]');
    ok('event-choice resolves the encounter',
      (await page.$$('[data-action="event-finish"]')).length === 1);
    await click('[data-action="event-finish"]');
    ok('event-finish returns to the map', await shown('screen-map') === 'flex');

    await state(() => { initiateCamp(); });
    await page.waitForTimeout(200);
    await click('[data-action="camp-choice"][data-kind="FORAGE"]');
    ok('camp-choice resolves the camp', (await page.$$('[data-action="camp-finish"]')).length === 1);
    await click('[data-action="camp-finish"]');
    ok('camp-finish returns to the map', await shown('screen-map') === 'flex');

    // ---- sector advance ----
    await state(() => { currentTier = TOTAL_TIERS + 1; renderMap(); });
    await click('[data-action="advance-sector"]');
    ok('advance-sector moves to the next sector',
      await state(() => currentSector) === 2 && await state(() => currentTier) === 1);

    // ---- run end ----
    await state(() => { initiateCombat('RAIDERS', false); playerRoster.forEach(c => c.hp = 0); checkWinState(); });
    await page.waitForTimeout(200);
    await click('[data-action="end-run"]');
    ok('end-run shows the run summary', await shown('screen-runover') === 'flex');

    // ---- erase save ----
    page.once('dialog', d => d.accept());
    await state(() => { currentSlot = 3; saveGameState(); renderTitleScreen(); openSettings(); });
    await click('[data-action="erase-save"]');
    ok('erase-save clears the slot',
      await state(() => localStorage.getItem(BASE_SAVE_KEY + 3)) === null);

    await state(() => { currentSlot = 1; confirmNewGame(1.0); openSettings(); });
    await click('[data-action="return-title"]');
    ok('return-title leaves the run', await shown('screen-title') === 'flex');
  }
};
